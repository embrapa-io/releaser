<?php

/**
 * Comando `io` no host: um wrapper em /usr/local/bin/io que roda `docker exec
 * [-it|-i] releaser io "$@"`, para que `io backup --all && io cloud --all`
 * funcione direto no terminal do servidor, no cron e em scripts, sem
 * `docker exec -it releaser`.
 *
 * O Releaser instala o wrapper pelo próprio socket do Docker (que já equivale a
 * root no host, então isto não dá poder novo): um contêiner auxiliar efêmero da
 * própria imagem (como o BackupVolume) com `-v /usr/local/bin:/target` grava o
 * script, de forma atômica (.io.tmp + mv: o sh lê o script aos poucos enquanto
 * ele roda, e sobrescrever no lugar quebraria a chamada em curso). Um
 * /usr/local/bin/io que não leve o cabeçalho MARK (não foi gerado pelo Releaser)
 * nunca é sobrescrito nem removido.
 *
 * Atualização automática: o wrapper repassa a versão da imagem que o gerou em
 * IO_WRAPPER_VERSION a cada chamada; quando ela difere de IO_RELEASER_VERSION
 * (imagem atualizada), autoUpdate () regrava o wrapper sem perguntar e avisa
 * numa linha. Se a regravação falhar (Docker via snap/AppArmor, rootless,
 * /usr/local/bin só leitura), avisa uma vez por versão (marca em /data/.cli)
 * com o comando manual. Chamadas com a mesma versão, ou sem a variável (docker
 * exec direto, cron interno, daemon), não fazem nada.
 */
class Cli
{
    const DOCKER = '/usr/bin/docker';

    // Destino no host e ponto de montagem no auxiliar.
    const TARGET = '/usr/local/bin';
    const MOUNT = '/target';
    const NAME = 'io';

    // Cabeçalho que identifica um wrapper gerado pelo Releaser (nunca mude: os antigos precisam casar).
    const MARK = '# Embrapa I/O Releaser host wrapper';

    // Alternativa manual, para quando o auxiliar não consegue gravar no host.
    const MANUAL = 'docker exec releaser io cli --print | sudo tee /usr/local/bin/io > /dev/null && sudo chmod +x /usr/local/bin/io';

    // Imagem padrão procurada pelo wrapper quando o contêiner não tem o nome esperado.
    const IMAGE = 'embrapa/releaser';

    // /data/.cli: versão cuja regravação automática falhou (para avisar uma só vez).
    const STATE = '.cli';

    static public function version ()
    {
        $version = trim ((string) getenv ('IO_RELEASER_VERSION'));

        return $version !== '' ? $version : 'dev';
    }

    static public function path ()
    {
        return self::TARGET .'/'. self::NAME;
    }

    /** O script do wrapper (POSIX sh), com a versão e o nome da imagem desta instalação. */
    static public function script ()
    {
        $script = <<<'SH'
#!/bin/sh
__MARK__
# IO_WRAPPER_VERSION=__VERSION__
#
# Runs the 'io' command inside the Embrapa I/O Releaser container, so that
#   io backup --all && io cloud --all
# works right from the terminal of this server, from cron and from scripts.
# The exit code is the one of 'io' in the container.
#
# Generated by 'io cli' from the image __IMAGE__:__VERSION__ and updated by the
# Releaser itself when the image changes. Do not edit. To regenerate by hand:
#   docker exec releaser io cli --print | sudo tee /usr/local/bin/io > /dev/null && sudo chmod +x /usr/local/bin/io
# Set RELEASER_CONTAINER if the Releaser container is not named 'releaser'.

name="${RELEASER_CONTAINER:-releaser}"
image="__IMAGE__"

if ! err=$(docker version --format '{{.Server.Version}}' 2>&1 > /dev/null); then
  err=$(printf '%s\n' "$err" | head -n 1)

  case "$err" in
    *"permission denied"*) echo "io: no permission to talk to Docker (add your user to the 'docker' group, or use sudo)" >&2 ;;
    *) echo "io: Docker is not responding: ${err:-unknown error}" >&2 ;;
  esac

  exit 125
fi

if [ "$(docker inspect --format '{{.State.Running}}' "$name" 2> /dev/null)" != "true" ]; then
  # In Docker Swarm the task gets another name: look for the service label, then for the image.
  found=$(docker ps -q --filter "label=com.docker.swarm.service.name=$name")

  [ -z "$found" ] && found=$(docker ps --format '{{.ID}} {{.Image}}' | awk -v img="$image" '$2 == img || index($2, img ":") == 1 { print $1 }')

  if [ -z "$found" ]; then
    echo "io: Releaser container '$name' not found or not running (set RELEASER_CONTAINER to its name)" >&2

    exit 125
  fi

  if [ "$(printf '%s\n' "$found" | wc -l)" -gt 1 ]; then
    echo "io: more than one Releaser container is running; set RELEASER_CONTAINER to the right one:" >&2

    for id in $found; do docker ps --filter "id=$id" --format '  {{.Names}} ({{.Image}})' >&2; done

    exit 125
  fi

  name=$found
fi

# -it only when both the input and the output are a terminal (so it works in cron, pipes and &&)
if [ -t 0 ] && [ -t 1 ]; then tty=-it; else tty=-i; fi

exec docker exec $tty -e "IO_WRAPPER_VERSION=__VERSION__" "$name" io "$@"
SH;

        return str_replace ([ '__MARK__', '__VERSION__', '__IMAGE__' ], [ self::MARK, self::version (), self::imageName () ], $script) ."\n";
    }

    /**
     * Instala ou atualiza o wrapper no host pelo contêiner auxiliar. Devolve
     * 'installed' ou 'updated'. Exceção com código 3 se já existe um
     * /usr/local/bin/io que não é do Releaser; outro código se a montagem ou a
     * gravação falhou (a mensagem traz o motivo do Docker).
     */
    static public function install ($quiet = FALSE)
    {
        $installer = 'set -e; f='. self::MOUNT .'/'. self::NAME .'; '
            .'if [ -e "$f" ] && ! grep -q '. escapeshellarg (self::MARK) .' "$f"; then echo IO_CLI_NOT_OURS; exit 3; fi; '
            .'if [ -e "$f" ]; then s=IO_CLI_UPDATED; else s=IO_CLI_INSTALLED; fi; '
            .'printf %s "$IO_CLI_SCRIPT" | base64 -d > '. self::MOUNT .'/.io.tmp; '
            .'chmod 755 '. self::MOUNT .'/.io.tmp; '
            .'mv -f '. self::MOUNT .'/.io.tmp "$f"; '
            .'echo $s';

        $result = self::helper ($installer, [ 'IO_CLI_SCRIPT' => base64_encode (self::script ()) ], $quiet);

        $out = implode (' ', $result ['out']);

        if ($result ['code'] === 3 || strpos ($out, 'IO_CLI_NOT_OURS') !== FALSE)
            throw new Exception ("There is already a '". self::path () ."' on this server that was not generated by the Releaser (no '". self::MARK ."' header). Remove or rename it first", 3);

        if ($result ['code'] !== 0 || !preg_match ('/IO_CLI_(INSTALLED|UPDATED)/', $out, $m))
            throw new Exception ("Unable to write '". self::path () ."' on this server through a helper container (". self::reason ($result) .")", $result ['code'] ?: 1);

        return strtolower ($m [1]);
    }

    /** Remove o wrapper do host, só se for do Releaser. Devolve 'removed' ou 'absent'. */
    static public function uninstall ()
    {
        $remover = 'f='. self::MOUNT .'/'. self::NAME .'; '
            .'if [ ! -e "$f" ]; then echo IO_CLI_ABSENT; exit 0; fi; '
            .'if ! grep -q '. escapeshellarg (self::MARK) .' "$f"; then echo IO_CLI_NOT_OURS; exit 3; fi; '
            .'rm -f "$f" && echo IO_CLI_REMOVED';

        $result = self::helper ($remover);

        $out = implode (' ', $result ['out']);

        if ($result ['code'] === 3 || strpos ($out, 'IO_CLI_NOT_OURS') !== FALSE)
            throw new Exception ("'". self::path () ."' on this server was not generated by the Releaser (no '". self::MARK ."' header): not removing it", 3);

        if ($result ['code'] !== 0 || !preg_match ('/IO_CLI_(REMOVED|ABSENT)/', $out, $m))
            throw new Exception ("Unable to remove '". self::path () ."' through a helper container (". self::reason ($result) .")", $result ['code'] ?: 1);

        return strtolower ($m [1]);
    }

    /**
     * Chamado pelo run.php em toda execução: regrava o wrapper quando a versão
     * que ele repassa (IO_WRAPPER_VERSION) difere da da imagem. Nunca lança e
     * nunca aborta o comando pedido.
     */
    static public function autoUpdate ()
    {
        $wrapper = trim ((string) getenv ('IO_WRAPPER_VERSION'));

        if ($wrapper === '' || $wrapper === self::version ()) return;

        $state = self::state ();

        try
        {
            // silencioso: no meio de outro comando, basta a linha INFO abaixo (o io cli mostra o COMMAND)
            self::install (TRUE);

            echo "INFO > 'io' command on this server updated to ". self::version () ." (it was generated by ". $wrapper ."). \n";

            if (file_exists ($state)) @unlink ($state);
        }
        catch (\Throwable $e)
        {
            // avisa uma vez por versão: a marca guarda a versão cuja regravação falhou
            if (file_exists ($state) && trim ((string) @file_get_contents ($state)) === self::version ()) return;

            @file_put_contents ($state, self::version () ."\n");

            echo "WARNING > The 'io' command on this server was generated by ". $wrapper ." and could not be updated to ". self::version () ." (". $e->getMessage ().'). Update it by hand: '. self::MANUAL ." \n";
        }
    }

    /** Roda $sh num contêiner auxiliar da imagem do Releaser com /usr/local/bin do host em /target. */
    static private function helper ($sh, array $env = [], $quiet = FALSE)
    {
        $cmd = self::DOCKER .' run --rm --network none';

        foreach (array_keys ($env) as $name) $cmd .= ' -e '. $name;

        $cmd .= ' -v '. escapeshellarg (self::TARGET .':'. self::MOUNT) .' '. escapeshellarg (BackupVolume::image ()) .' sh -c '. escapeshellarg ($sh);

        if (!$quiet) echo 'COMMAND > '. $cmd ."\n";

        return BackupVolume::command ($cmd, $env);
    }

    // Nome da imagem (sem a tag) do contêiner do Releaser em execução, para o wrapper procurá-la; padrão embrapa/releaser.
    static private function imageName ()
    {
        $id = BackupVolume::container ();

        if ($id !== FALSE)
        {
            exec (self::DOCKER .' inspect --type container --format '. escapeshellarg ('{{.Config.Image}}') .' '. escapeshellarg ($id) .' 2> /dev/null', $output, $return);

            $image = trim ((string) ($output [0] ?? ''));

            if ($return === 0 && preg_match ('/^([a-z0-9][a-z0-9._\/-]*[a-z0-9])(:[A-Za-z0-9._-]+)?(@sha256:[0-9a-f]+)?$/', $image, $m)) return $m [1];
        }

        return self::IMAGE;
    }

    static private function reason ($result)
    {
        // O docker termina todo erro de 'run' com a dica "Run 'docker run --help' for more information": sem tirá-la,
        // a última linha seria ela, e o erro de fato (a linha anterior) se perderia.
        $lines = array_values (array_filter (array_merge ($result ['err'], $result ['out']), function ($line) {
            return strlen (trim ($line)) && !preg_match ("/^Run '.+ --help' for more information/", trim ($line));
        }));

        $last = sizeof ($lines) ? $lines [sizeof ($lines) - 1] : 'exit code '. $result ['code'];

        return mb_strimwidth (trim ($last), 0, 300, '...');
    }

    static private function state ()
    {
        global $_data;

        return ($_data ? $_data : DIRECTORY_SEPARATOR .'data') . DIRECTORY_SEPARATOR . self::STATE;
    }
}
