<?php

/**
 * `io cli [--print | --uninstall] [--yes]`: instala (ou atualiza) o comando `io`
 * no host, em /usr/local/bin/io, pelo contêiner auxiliar da própria imagem (ver
 * class/Cli.php). Variáveis do escopo: $_flags (opções recebidas).
 */

$_print = in_array ('--print', $_flags);
$_remove = in_array ('--uninstall', $_flags);
$_yes = in_array ('--yes', $_flags);

if ($_print)
{
	// normalmente nem chega aqui: o run.php imprime o script antes de qualquer outra saída
	echo Cli::script ();

	return;
}

$confirm = function ($question) use ($_yes)
{
	if ($_yes) return TRUE;

	echo $question ." (y/N): ";

	$line = fgets (STDIN);

	return $line !== FALSE && in_array (strtolower (trim ($line)), [ 'y', 'yes' ]);
};

if ($_remove)
{
	echo "INFO > This removes the 'io' command from this server ('". Cli::path () ."'), only if it was generated by the Releaser. \n";

	if (!$confirm ("Remove '". Cli::path () ."' from this server?"))
	{
		echo "INFO > Nothing done. \n";

		return;
	}

	try
	{
		$result = Cli::uninstall ();
	}
	catch (Exception $e)
	{
		echo "ERROR > ". $e->getMessage () ."! \n";

		if ($e->getCode () !== 3) echo "INFO > To remove it by hand: sudo rm ". Cli::path () ." \n";

		return;
	}

	echo "SUCCESS > ". ($result === 'removed' ? "'". Cli::path () ."' removed from this server." : "There is no '". Cli::path () ."' on this server; nothing to remove.") ." \n";

	return;
}

echo "INFO > This installs the 'io' command on this server, at '". Cli::path () ."', so that commands such as \n";
echo "       io backup --all && io cloud --all \n";
echo "       run right from the terminal of the server (and from cron), without 'docker exec -it releaser'. \n";
echo "INFO > A helper container of the Releaser image (version ". Cli::version ().") writes the script with '". Cli::TARGET ."' of the host mounted; the Docker socket already gives this power. \n";
echo "INFO > An existing '". Cli::path () ."' not generated by the Releaser is never overwritten. The Releaser updates the script itself when the image changes. \n";

if (!$confirm ("Install (or update) '". Cli::path () ."' on this server?"))
{
	echo "INFO > Nothing done. Use 'io cli --print' to see the script. \n";

	return;
}

try
{
	$result = Cli::install ();
}
catch (Exception $e)
{
	echo "ERROR > ". $e->getMessage () ."! \n";

	if ($e->getCode () !== 3 && Cli::snap ($e->getMessage ()))
	{
		echo "INFO > On this server, Docker appears to be installed by Snap, whose confinement does not let the helper container write on the host. In this case, to install the 'io' command, run on the server: \n";
		echo "       ". Cli::MANUAL ." \n";
	}
	elseif ($e->getCode () !== 3)
	{
		echo "INFO > Docker installed via snap (AppArmor), rootless Docker or a read-only '". Cli::TARGET ."' can prevent the helper container from writing on the host. Install the script by hand, from the server: \n";
		echo "       ". Cli::MANUAL ." \n";
	}

	return;
}

echo "SUCCESS > 'io' command ". $result ." at '". Cli::path () ."' (version ". Cli::version ()."). From now on, in the terminal of the server: io [COMMAND]. \n";
