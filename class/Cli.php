<?php

/**
 * Comando `io` no host: um wrapper em /usr/local/bin/io que roda `docker exec
 * [-it|-i] releaser io "$@"`, para que `io backup --all && io cloud --all`
 * funcione direto no terminal do servidor, no cron e em scripts, sem
 * `docker exec -it releaser`.
 *
 * O Releaser instala o wrapper pelo próprio socket do Docker (que já equivale a
 * root no host, então isto não dá poder novo): um contêiner auxiliar efêmero da
 * própria imagem (como o BackupVolume) com `-v /usr/local/bin:/target` grava o
 * script, de forma atômica (.io.tmp + mv: o sh lê o script aos poucos enquanto
 * ele roda, e sobrescrever no lugar quebraria a chamada em curso). Um
 * /usr/local/bin/io que não leve o cabeçalho MARK (não foi gerado pelo Releaser)
 * nunca é sobrescrito nem removido.
 *
 * Atualização automática: o wrapper repassa a versão da imagem que o gerou em
 * IO_WRAPPER_VERSION a cada chamada; quando ela difere de IO_RELEASER_VERSION
 * (imagem atualizada), autoUpdate () regrava o wrapper sem perguntar e avisa
 * numa linha. Se a regravação falhar (Docker via snap/AppArmor, rootless,
 * /usr/local/bin só leitura), avisa uma vez por versão (marca em /data/.cli)
 * com o comando manual. Chamadas com a mesma versão, ou sem a variável (docker
 * exec direto, cron interno, daemon), não fazem nada.
 *
 * Contêiner fora do ar (desde a 1.26.11-4): antes, o wrapper só dizia "not found
 * or not running". Agora distingue o contêiner PARADO (mostra e oferece o
 * `docker start`) do REMOVIDO (mostra e oferece o `docker run` que o recria).
 * O `docker run` é montado aqui, na geração do wrapper, a partir do inspect do
 * próprio contêiner (recreate ()): nome, montagens, política de reinício,
 * --add-host, --dns, rede e a imagem pela TAG EXATA da versão em execução. Nunca
 * `embrapa/releaser` sem tag: num servidor atualizado pelo `io upgrade`, o
 * `latest` local é o da instalação, e recriar por ele rebaixaria a versão. A
 * pergunta só é feita em terminal; em cron, scripts e pipes, o wrapper mostra o
 * comando e sai com 125, como antes. Swarm e Docker Compose ficam de fora (o
 * serviço ou o arquivo do compose é que recria).
 */
class Cli
{
    const DOCKER = '/usr/bin/docker';

    // Destino no host e ponto de montagem no auxiliar.
    const TARGET = '/usr/local/bin';
    const MOUNT = '/target';
    const NAME = 'io';

    // Cabeçalho que identifica um wrapper gerado pelo Releaser (nunca mude: os antigos precisam casar).
    const MARK = '# Embrapa I/O Releaser host wrapper';

    // Alternativa manual, para quando o auxiliar não consegue gravar no host.
    const MANUAL = 'docker exec releaser io cli --print | sudo tee /usr/local/bin/io > /dev/null && sudo chmod +x /usr/local/bin/io';

    // Imagem padrão procurada pelo wrapper quando o contêiner não tem o nome esperado.
    const IMAGE = 'embrapa/releaser';

    // /data/.cli: versão cuja regravação automática falhou (para avisar uma só vez).
    const STATE = '.cli';

    static public function version ()
    {
        $version = trim ((string) getenv ('IO_RELEASER_VERSION'));

        return $version !== '' ? $version : 'dev';
    }

    static public function path ()
    {
        return self::TARGET .'/'. self::NAME;
    }

    /**
     * O Docker do host foi instalado pelo snap? O daemon confinado tem raiz própria e somente leitura e não enxerga
     * o /usr/local/bin do host ("mkdir /usr/local/bin: read-only file system"), então o auxiliar nunca grava: só o
     * caminho manual (MANUAL) funciona. Detecta pelo diretório de dados do daemon (/var/snap/docker/...) e, na falta
     * dele, pela mensagem de erro do Docker.
     */
    static public function snap ($message = '')
    {
        exec (self::DOCKER .' info --format '. escapeshellarg ('{{.DockerRootDir}}') .' 2> /dev/null', $output, $return);

        if ($return === 0 && strpos ((string) ($output [0] ?? ''), '/snap/') !== FALSE) return TRUE;

        return strpos ($message, 'mkdir '. self::TARGET .': read-only file system') !== FALSE;
    }

    /**
     * O script do wrapper (POSIX sh), com a versão e o nome da imagem desta
     * instalação e o comando que recria o contêiner ($recreate; NULL = o do
     * contêiner em execução, ver recreate ()).
     */
    static public function script ($recreate = NULL)
    {
        if ($recreate === NULL) $recreate = self::recreate ();

        $script = <<<'SH'
#!/bin/sh
__MARK__
# IO_WRAPPER_VERSION=__VERSION__
#
# Runs the 'io' command inside the Embrapa I/O Releaser container, so that
#   io backup --all && io cloud --all
# works right from the terminal of this server, from cron and from scripts.
# The exit code is the one of 'io' in the container.
#
# Generated by 'io cli' from the image __IMAGE__:__VERSION__ and updated by the
# Releaser itself when the image changes. Do not edit. To regenerate by hand:
#   docker exec releaser io cli --print | sudo tee /usr/local/bin/io > /dev/null && sudo chmod +x /usr/local/bin/io
# Set RELEASER_CONTAINER if the Releaser container is not named 'releaser'.
#
# If the container is stopped or was removed, this script shows how to bring it
# back and, on a terminal, offers to do it (never from cron or scripts).

name="${RELEASER_CONTAINER:-releaser}"
image="__IMAGE__"

# The container as it was when this script was generated: its name and the
# command that creates it again (empty when it is not a plain 'docker run').
created=__CREATED__
recreate=__RECREATE__
note=__NOTE__

# Asks on the terminal; without one (cron, scripts, pipes), the answer is no.
confirm() {
  [ -t 0 ] && [ -t 2 ] || return 1

  printf '%s (y/N): ' "$1" >&2

  read -r answer || return 1

  case "$answer" in y|Y|yes|Yes|YES) return 0 ;; esac

  return 1
}

if ! err=$(docker version --format '{{.Server.Version}}' 2>&1 > /dev/null); then
  err=$(printf '%s\n' "$err" | head -n 1)

  case "$err" in
    *"permission denied"*) echo "io: no permission to talk to Docker (add your user to the 'docker' group, or use sudo)" >&2 ;;
    *) echo "io: Docker is not responding: ${err:-unknown error}" >&2 ;;
  esac

  exit 125
fi

if [ "$(docker inspect --format '{{.State.Running}}' "$name" 2> /dev/null)" != "true" ]; then
  # In Docker Swarm the task gets another name: look for the service label, then for the image.
  found=$(docker ps -q --filter "label=com.docker.swarm.service.name=$name")

  [ -z "$found" ] && found=$(docker ps --format '{{.ID}} {{.Image}}' | awk -v img="$image" '$2 == img || index($2, img ":") == 1 { print $1 }')

  if [ -z "$found" ]; then
    status=$(docker inspect --type container --format '{{.State.Status}}' "$name" 2> /dev/null)

    if [ -n "$status" ]; then
      echo "io: the Releaser container '$name' exists, but it is not running (status: $status). To start it:" >&2
      echo "  docker start $name" >&2

      confirm "Start it now?" || exit 125

      docker start "$name" > /dev/null || exit 125
    elif [ -n "$recreate" ] && [ "$name" = "$created" ]; then
      echo "io: the Releaser container '$name' was not found on this server (removed?). To create it again, as it" >&2
      echo "was when this command was generated (version __VERSION__):" >&2
      echo "  $recreate" >&2

      [ -n "$note" ] && echo "$note" >&2

      confirm "Create it now?" || exit 125

      sh -c "$recreate" > /dev/null || exit 125
    else
      echo "io: Releaser container '$name' not found or not running (set RELEASER_CONTAINER to its name)" >&2

      exit 125
    fi

    # waits for the container to be up before running the command in it
    tries=0

    while [ "$(docker inspect --format '{{.State.Running}}' "$name" 2> /dev/null)" != "true" ]; do
      tries=$((tries + 1))

      if [ "$tries" -gt 15 ]; then
        echo "io: the Releaser container '$name' did not stay up; see: docker logs $name" >&2

        exit 125
      fi

      sleep 1
    done

    echo "io: the Releaser container '$name' is running." >&2

    found=$name
  fi

  if [ "$(printf '%s\n' "$found" | wc -l)" -gt 1 ]; then
    echo "io: more than one Releaser container is running; set RELEASER_CONTAINER to the right one:" >&2

    for id in $found; do docker ps --filter "id=$id" --format '  {{.Names}} ({{.Image}})' >&2; done

    exit 125
  fi

  name=$found
fi

# -it only when both the input and the output are a terminal (so it works in cron, pipes and &&)
if [ -t 0 ] && [ -t 1 ]; then tty=-it; else tty=-i; fi

exec docker exec $tty -e "IO_WRAPPER_VERSION=__VERSION__" "$name" io "$@"
SH;

        return str_replace (
            [ '__MARK__', '__VERSION__', '__IMAGE__', '__CREATED__', '__RECREATE__', '__NOTE__' ],
            [ self::MARK, self::version (), self::imageName (), self::sh ($recreate ['name']), self::sh ($recreate ['command']), self::sh ($recreate ['note']) ],
            $script
        ) ."\n";
    }

    /**
     * O `docker run` que recria o contêiner do Releaser em execução, para o
     * wrapper mostrar e oferecer quando o contêiner tiver sido removido (ver
     * command ()). Tudo vazio quando não dá para saber. Nunca lança.
     */
    static public function recreate ()
    {
        $none = [ 'name' => '', 'command' => '', 'note' => '' ];

        try
        {
            $id = BackupVolume::container ();

            if ($id === FALSE) return $none;

            exec (self::DOCKER .' inspect --type container '. escapeshellarg ($id) .' 2> /dev/null', $output, $return);

            $inspect = json_decode (implode ("\n", $output));

            if ($return !== 0 || !is_array ($inspect) || !isset ($inspect [0]) || !is_object ($inspect [0])) return $none;

            // variáveis que a imagem já define, para separar as que foram passadas na criação do contêiner
            $defined = NULL;

            unset ($output);

            exec (self::DOCKER .' inspect --type image --format '. escapeshellarg ('{{json .Config.Env}}') .' '. escapeshellarg ((string) ($inspect [0]->Image ?? '')) .' 2> /dev/null', $output, $return);

            $env = json_decode ((string) ($output [0] ?? ''), TRUE);

            if ($return === 0 && is_array ($env)) $defined = $env;

            return self::command ($inspect [0], self::version (), $defined);
        }
        catch (\Throwable $e)
        {
            return $none;
        }
    }

    /**
     * Monta, do inspect de um contêiner ($container, stdClass), o `docker run`
     * que o recria: ['name' => nome, 'command' => comando, 'note' => aviso]. Pura
     * (testes em tests/cli.php).
     *
     *   - nome, montagens (HostConfig.Binds, na ordem), política de reinício,
     *     --add-host, --dns e rede que não seja a padrão;
     *   - imagem pela tag exata de $version quando ela é de uma versão publicada
     *     (MAJOR.AA.M-N); em desenvolvimento, a imagem como o contêiner a nomeia;
     *   - variáveis de ambiente passadas na criação ($imageEnv: as que a imagem
     *     define; NULL = desconhecidas) ficam FORA do comando, porque o script é
     *     legível por qualquer usuário do servidor: só os nomes vão para o aviso.
     *
     * Tudo vazio para contêiner de serviço do Swarm ou do Docker Compose (quem
     * recria é o serviço ou o arquivo do compose) e sem /data ou sem o socket do
     * Docker entre as montagens.
     */
    static public function command ($container, $version, array $imageEnv = NULL)
    {
        $none = [ 'name' => '', 'command' => '', 'note' => '' ];

        $labels = (array) ($container->Config->Labels ?? []);

        if (isset ($labels ['com.docker.swarm.service.name']) || isset ($labels ['com.docker.compose.project'])) return $none;

        $name = ltrim ((string) ($container->Name ?? ''), '/');

        if (!preg_match ('/^[A-Za-z0-9][A-Za-z0-9_.-]*$/', $name)) return $none;

        $binds = array_values (array_filter ((array) ($container->HostConfig->Binds ?? []), 'is_string'));

        $targets = array_map (function ($bind) { return explode (':', $bind) [1] ?? ''; }, $binds);

        if (!in_array ('/data', $targets, TRUE) || !in_array ('/var/run/docker.sock', $targets, TRUE)) return $none;

        $args = [ 'docker', 'run', '-d', '--name', $name ];

        foreach ($binds as $bind) { $args [] = '-v'; $args [] = $bind; }

        $policy = (string) ($container->HostConfig->RestartPolicy->Name ?? '');

        $retries = intval ($container->HostConfig->RestartPolicy->MaximumRetryCount ?? 0);

        if (!empty ($container->HostConfig->AutoRemove))
            $args [] = '--rm';
        elseif ($policy !== '' && $policy !== 'no')
        {
            $args [] = '--restart';
            $args [] = $policy . ($policy === 'on-failure' && $retries > 0 ? ':'. $retries : '');
        }

        foreach ((array) ($container->HostConfig->ExtraHosts ?? []) as $host)
            if (is_string ($host) && $host !== '') { $args [] = '--add-host'; $args [] = $host; }

        foreach ((array) ($container->HostConfig->Dns ?? []) as $dns)
            if (is_string ($dns) && $dns !== '') { $args [] = '--dns'; $args [] = $dns; }

        $mode = (string) ($container->HostConfig->NetworkMode ?? 'default');

        if (!in_array ($mode, [ '', 'default', 'bridge' ], TRUE)) { $args [] = '--network'; $args [] = $mode; }

        $configured = (string) ($container->Config->Image ?? '');

        // repositório sem a tag nem o digest; a tag é o que vem depois do último ':' que esteja depois da
        // última '/' (o ':' de 'registro:5000/io/releaser' é da porta). Imagem dada pelo ID não tem repositório.
        $repository = preg_replace ('/@sha256:[0-9a-f]+$/', '', $configured);

        $colon = strrpos ($repository, ':');

        if ($colon !== FALSE && $colon > intval (strrpos ($repository, '/'))) $repository = substr ($repository, 0, $colon);

        if (preg_match ('/^(sha256:)?[0-9a-f]{12,64}$/', $configured) || !preg_match ('/^[a-z0-9][a-z0-9._\/:-]*[a-z0-9]$/', $repository)) $repository = self::IMAGE;

        if (preg_match ('/^[0-9]+\.[0-9]{2}\.[0-9]+-[0-9]+$/', (string) $version))
            $args [] = $repository .':'. $version;
        else
            $args [] = $configured !== '' ? $configured : self::IMAGE;

        $note = '';

        if ($imageEnv !== NULL)
        {
            $names = function ($list) { return array_map (function ($pair) { return explode ('=', (string) $pair, 2) [0]; }, (array) $list); };

            $extra = array_values (array_diff ($names ($container->Config->Env ?? []), $names ($imageEnv)));

            if (sizeof ($extra))
                $note = 'It was created with environment variables that are not in the command above; add each one with -e NAME=value: '. implode (', ', $extra);
        }

        return [ 'name' => $name, 'command' => implode (' ', array_map ([ self::class, 'quote' ], $args)), 'note' => $note ];
    }

    // Argumento para a linha de comando mostrada: sem aspas quando não precisa, para ficar legível.
    static private function quote ($arg)
    {
        return preg_match ('/^[A-Za-z0-9_.,:\/@=+-]+$/', $arg) ? $arg : escapeshellarg ($arg);
    }

    // Literal de sh entre aspas simples, para os valores gravados no script.
    static private function sh ($value)
    {
        return "'". str_replace ("'", "'\\''", (string) $value) ."'";
    }

    /**
     * Instala ou atualiza o wrapper no host pelo contêiner auxiliar. Devolve
     * 'installed' ou 'updated'. Exceção com código 3 se já existe um
     * /usr/local/bin/io que não é do Releaser; outro código se a montagem ou a
     * gravação falhou (a mensagem traz o motivo do Docker).
     */
    static public function install ($quiet = FALSE)
    {
        $installer = 'set -e; f='. self::MOUNT .'/'. self::NAME .'; '
            .'if [ -e "$f" ] && ! grep -q '. escapeshellarg (self::MARK) .' "$f"; then echo IO_CLI_NOT_OURS; exit 3; fi; '
            .'if [ -e "$f" ]; then s=IO_CLI_UPDATED; else s=IO_CLI_INSTALLED; fi; '
            .'printf %s "$IO_CLI_SCRIPT" | base64 -d > '. self::MOUNT .'/.io.tmp; '
            .'chmod 755 '. self::MOUNT .'/.io.tmp; '
            .'mv -f '. self::MOUNT .'/.io.tmp "$f"; '
            .'echo $s';

        $result = self::helper ($installer, [ 'IO_CLI_SCRIPT' => base64_encode (self::script ()) ], $quiet);

        $out = implode (' ', $result ['out']);

        if ($result ['code'] === 3 || strpos ($out, 'IO_CLI_NOT_OURS') !== FALSE)
            throw new Exception ("There is already a '". self::path () ."' on this server that was not generated by the Releaser (no '". self::MARK ."' header). Remove or rename it first", 3);

        if ($result ['code'] !== 0 || !preg_match ('/IO_CLI_(INSTALLED|UPDATED)/', $out, $m))
            throw new Exception ("Unable to write '". self::path () ."' on this server through a helper container (". self::reason ($result) .")", $result ['code'] ?: 1);

        return strtolower ($m [1]);
    }

    /** Remove o wrapper do host, só se for do Releaser. Devolve 'removed' ou 'absent'. */
    static public function uninstall ()
    {
        $remover = 'f='. self::MOUNT .'/'. self::NAME .'; '
            .'if [ ! -e "$f" ]; then echo IO_CLI_ABSENT; exit 0; fi; '
            .'if ! grep -q '. escapeshellarg (self::MARK) .' "$f"; then echo IO_CLI_NOT_OURS; exit 3; fi; '
            .'rm -f "$f" && echo IO_CLI_REMOVED';

        $result = self::helper ($remover);

        $out = implode (' ', $result ['out']);

        if ($result ['code'] === 3 || strpos ($out, 'IO_CLI_NOT_OURS') !== FALSE)
            throw new Exception ("'". self::path () ."' on this server was not generated by the Releaser (no '". self::MARK ."' header): not removing it", 3);

        if ($result ['code'] !== 0 || !preg_match ('/IO_CLI_(REMOVED|ABSENT)/', $out, $m))
            throw new Exception ("Unable to remove '". self::path () ."' through a helper container (". self::reason ($result) .")", $result ['code'] ?: 1);

        return strtolower ($m [1]);
    }

    /**
     * Chamado pelo run.php em toda execução: regrava o wrapper quando a versão
     * que ele repassa (IO_WRAPPER_VERSION) difere da da imagem. Nunca lança e
     * nunca aborta o comando pedido.
     */
    static public function autoUpdate ()
    {
        $wrapper = trim ((string) getenv ('IO_WRAPPER_VERSION'));

        if ($wrapper === '' || $wrapper === self::version ()) return;

        $state = self::state ();

        try
        {
            // silencioso: no meio de outro comando, basta a linha INFO abaixo (o io cli mostra o COMMAND)
            self::install (TRUE);

            echo "INFO > 'io' command on this server updated to ". self::version () ." (it was generated by ". $wrapper ."). \n";

            if (file_exists ($state)) @unlink ($state);
        }
        catch (\Throwable $e)
        {
            // avisa uma vez por versão: a marca guarda a versão cuja regravação falhou
            if (file_exists ($state) && trim ((string) @file_get_contents ($state)) === self::version ()) return;

            @file_put_contents ($state, self::version () ."\n");

            $why = self::snap ($e->getMessage ()) ? 'Docker appears to be installed by Snap on this server, so it must be updated by hand' : $e->getMessage ();

            echo "WARNING > The 'io' command on this server was generated by ". $wrapper ." and could not be updated to ". self::version () ." (". $why .'). Update it by hand: '. self::MANUAL ." \n";
        }
    }

    /** Roda $sh num contêiner auxiliar da imagem do Releaser com /usr/local/bin do host em /target. */
    static private function helper ($sh, array $env = [], $quiet = FALSE)
    {
        $cmd = self::DOCKER .' run --rm --network none';

        foreach (array_keys ($env) as $name) $cmd .= ' -e '. $name;

        $cmd .= ' -v '. escapeshellarg (self::TARGET .':'. self::MOUNT) .' '. escapeshellarg (BackupVolume::image ()) .' sh -c '. escapeshellarg ($sh);

        if (!$quiet) echo 'COMMAND > '. $cmd ."\n";

        return BackupVolume::command ($cmd, $env);
    }

    // Nome da imagem (sem a tag) do contêiner do Releaser em execução, para o wrapper procurá-la; padrão embrapa/releaser.
    static private function imageName ()
    {
        $id = BackupVolume::container ();

        if ($id !== FALSE)
        {
            exec (self::DOCKER .' inspect --type container --format '. escapeshellarg ('{{.Config.Image}}') .' '. escapeshellarg ($id) .' 2> /dev/null', $output, $return);

            $image = trim ((string) ($output [0] ?? ''));

            if ($return === 0 && preg_match ('/^([a-z0-9][a-z0-9._\/-]*[a-z0-9])(:[A-Za-z0-9._-]+)?(@sha256:[0-9a-f]+)?$/', $image, $m)) return $m [1];
        }

        return self::IMAGE;
    }

    static private function reason ($result)
    {
        // O docker termina todo erro de 'run' com a dica "Run 'docker run --help' for more information": sem tirá-la,
        // a última linha seria ela, e o erro de fato (a linha anterior) se perderia.
        $lines = array_values (array_filter (array_merge ($result ['err'], $result ['out']), function ($line) {
            return strlen (trim ($line)) && !preg_match ("/^Run '.+ --help' for more information/", trim ($line));
        }));

        $last = sizeof ($lines) ? $lines [sizeof ($lines) - 1] : 'exit code '. $result ['code'];

        return mb_strimwidth (trim ($last), 0, 300, '...');
    }

    static private function state ()
    {
        global $_data;

        return ($_data ? $_data : DIRECTORY_SEPARATOR .'data') . DIRECTORY_SEPARATOR . self::STATE;
    }
}
