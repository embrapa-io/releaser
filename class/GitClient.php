<?php

class GitClient
{
    const GIT = '/usr/bin/git';

    static private $single = FALSE;

    private $ssh = 'ssh://git@git.embrapa.io';

    private final function __construct ()
	{
        $ssh = trim (getenv ('GITLAB_SSH'));

        if ($ssh != '') $this->ssh = $ssh;

        exec (self::GIT .' config --global user.email "releaser@embrapa.io"');
        exec (self::GIT .' config --global user.name "Embrapa I/O Releaser"');
    }

    static public function singleton ()
	{
		if (self::$single !== FALSE)
			return self::$single;

		$class = __CLASS__;

		self::$single = new $class ();

		return self::$single;
	}

    /**
     * Grava os arquivos de ambiente no clone. Antes o teste era '!file_put_contents',
     * e um .env vazio (build sem variáveis) gravava 0 bytes e era tomado por falha
     * (mesmo bug do deployer da plataforma, aplicativo-cibe, 21/10/2026). Também avisa
     * quando o repositório versiona esses arquivos, que não deveriam estar no Git.
     */
    private function writeEnvFiles ($clone, $files)
    {
        exec (self::GIT .' -C '. escapeshellarg ($clone) .' ls-files -- '. implode (' ', array_map ('escapeshellarg', array_keys ($files))) .' 2>/dev/null', $tracked);

        if (sizeof ($tracked))
            echo "WARNING > The repository versions the file(s) ". implode (', ', $tracked) .", which must NOT be in Git (they hold secrets and are generated by the Releaser on each deploy). Remove them from the repository with 'git rm --cached ". implode (' ', $tracked) ."', add them to '.gitignore' and commit. \n";

        foreach ($files as $name => $content)
        {
            $file = $clone . DIRECTORY_SEPARATOR . $name;

            if (is_dir ($file))
                throw new Exception ("Impossible to write '". $name ."' file: the repository has a directory with this name. Remove it from the repository");

            // O handleError transforma o warning do PHP em exceção; o motivo vai junto.
            try
            {
                $written = file_put_contents ($file, $content, LOCK_EX);
            }
            catch (\Throwable $e)
            {
                throw new Exception ("Impossible to write '". $name ."' file (". $e->getMessage () .")");
            }

            if ($written === FALSE)
                throw new Exception ("Impossible to write '". $name ."' file");
        }
    }

    static public function delete ($path)
    {
        if (!file_exists ($path)) return;

        $files = new RecursiveIteratorIterator (
            new RecursiveDirectoryIterator ($path, RecursiveDirectoryIterator::SKIP_DOTS),
            RecursiveIteratorIterator::CHILD_FIRST);

        foreach ($files as $fileinfo)
        {
            $todo = ($fileinfo->isDir () ? 'rmdir' : 'unlink');
            $todo ($fileinfo->getRealPath ());
        }

        rmdir ($path);
    }

    static public function copy ($from, $to)
    {
        if (!file_exists ($from) || !is_dir ($from) || !file_exists ($to) || !is_dir ($to)) return;

        $files = new RecursiveIteratorIterator (
            new RecursiveDirectoryIterator ($from, RecursiveDirectoryIterator::SKIP_DOTS),
            RecursiveIteratorIterator::SELF_FIRST);

        foreach ($files as $f)
            if ($f->isDir ())
                mkdir ($to . DIRECTORY_SEPARATOR . $files->getSubPathname ());
            else
                copy ($f, $to . DIRECTORY_SEPARATOR . $files->getSubPathname ());
    }

    public function cloneTag ($project, $app, $stage, $version, $ci, $bk, $env, $path)
    {
        if (!file_exists ($path) || !is_dir ($path)) mkdir ($path);

        chdir ($path);

        $clone = $path . DIRECTORY_SEPARATOR . implode (DIRECTORY_SEPARATOR, [$project, $app, $version]);

        if (file_exists ($clone)) self::delete ($clone);

        mkdir ($clone, 0777, TRUE);

        exec (self::GIT .' clone --depth 1 --verbose --branch '. $version .' '. $this->ssh .'/'. $project .'/'. $app .'.git '. $clone .' 2>&1', $output, $return);

        if ($return !== 0)
        {
            self::delete ($clone);

            echo "\n". implode ("\n", $output) ."\n";

            throw new Exception ('Impossible to clone repository at tag "'. $version .'"');
        }

        unset ($output);
        unset ($return);

        exec (self::GIT .' config --global --add safe.directory '. $clone .' 2>&1', $output, $return);

        if ($return !== 0)
            echo "\n". implode ("\n", $output) ."\n";

        try
        {
            $this->writeEnvFiles ($clone, [ '.env' => $env, '.env.io' => $ci, '.env.sh' => $bk ]);
        }
        catch (Exception $e)
        {
            self::delete ($clone);

            throw $e;
        }

        return $clone;
    }

    public function cloneBranch ($project, $app, $stage, $ci, $bk, $env)
    {
        $tmp = DIRECTORY_SEPARATOR .'tmp'. DIRECTORY_SEPARATOR .'validate';

        if (!file_exists ($tmp)) mkdir ($tmp);

        chdir ($tmp);

        $clone = $tmp . DIRECTORY_SEPARATOR . $project .'_'. $app .'_'. $stage;

        if (file_exists ($clone)) self::delete ($clone);

        mkdir ($clone);

        exec (self::GIT .' clone --depth 1 --verbose --branch '. $stage .' '. $this->ssh .'/'. $project .'/'. $app .'.git '. $clone .' 2>&1', $output, $return);

        if ($return !== 0)
        {
            self::delete ($clone);

            throw new Exception ('Impossible to clone repository at branch "'. $stage .'"');
        }

        try
        {
            $this->writeEnvFiles ($clone, [ '.env' => $env, '.env.io' => $ci, '.env.sh' => $bk ]);
        }
        catch (Exception $e)
        {
            self::delete ($clone);

            throw $e;
        }

        return $clone;
    }
}